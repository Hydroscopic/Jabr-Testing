using System;
using System.Linq;


using AVcontrol;



namespace JabrAPI
{
    public partial class Noisifier
    {
        private readonly SecureRandom _random = new(128);  //  Reseed after every 128 generated bytes (min possible amount)
        public  Noise.Settings settings = new();

        private readonly SetHelper _setHelper;
        private readonly ValidateHelper _validateHelper;

        private Byte[] _primaryNoise = [];
        private Byte[] _complexNoise = [];

        private Byte[] _banned = [];
        private Byte _primaryCount = 8;
        private Byte _complexCount = 16;



        public Noisifier(Byte[] primaryNoise, Byte[] complexNoise)
        {
            _setHelper = new(this);
            _validateHelper = new(this);

            _primaryNoise = primaryNoise;
            _complexNoise = complexNoise;
        }
        public Noisifier(Noisifier otherNoisifier, bool fullCopy = true)
        {
            _setHelper = new(this);
            _validateHelper = new(this);

            CopyFrom(otherNoisifier, fullCopy);
        }

        public Noisifier(bool autoGenerate, Byte[] banned)
        {
            _setHelper = new(this);
            _validateHelper = new(this);

            Set.Banned(banned);
            if (autoGenerate) ReGenerate(false);
            else Set.Banned(banned);
        }

        public Noisifier(Byte[] binaryExportData, bool throwExceptions = false)
        {
            _setHelper = new(this);
            _validateHelper = new(this);

            ImportFromBinary(binaryExportData, throwExceptions);
        }
        public Noisifier()
        {
            _setHelper = new(this);
            _validateHelper = new(this);
        }



        public Byte[] PrimaryNoise => _primaryNoise;
        public Byte[] ComplexNoise => _complexNoise;
        public Byte[] Banned => _banned;

        public UInt64 RandomReseedInterval
        {
            get;
            set
            {
                field = value >= 128 ? value : 128;
                _random.UpdateReseedInterval(field);
            }
        }


        public Byte RandomPrimaryByte => _primaryNoise[_random.Next(_primaryNoise.Length)];
        public Byte[] RandomPrimarySequence(Int32 count) =>
            [..
                Enumerable.Range(0, count).Select
                (
                    _ => _primaryNoise[_random.Next(_primaryNoise.Length)]
                )
            ];
        public Byte[] RandomComplexSequence(Int32 count) =>
            [..
                Enumerable.Range(0, count).Select
                (
                    _ => _complexNoise[_random.Next(_complexNoise.Length)]
                )
            ];
    }
}